"""Markdown rendering for Anti Briefs and Anti Memos with [S#] citations and a Sources list."""

from __future__ import annotations

from typing import Any

from radar.agent.brief_schema import AntiBrief, AntiMemo, Claim, MeetingBrief

UNKNOWN = "Unknown — no evidence collected."

_BRIEF_SECTIONS: tuple[tuple[str, str], ...] = (
    ("what_they_do", "What they do"),
    ("why_now", "Why now"),
    ("what_changed", "What changed"),
    ("founders", "Founders"),
    ("technical_edge", "Technical edge"),
    ("market", "Market"),
    ("competitors", "Competitors"),
    ("why_this_could_matter", "Why this could matter"),
    ("why_this_could_be_wrong", "Why this could be wrong"),
    ("contradictory_signals", "Contradictory signals"),
    ("signals", "Key signals"),
)

_MEMO_SECTIONS: tuple[tuple[str, str], ...] = (
    ("why_on_radar", "Why it is on our radar"),
    ("why_now", "Why now"),
    ("founders", "Founders"),
    ("technical_insight", "Technical insight"),
    ("what_others_may_be_missing", "What others may be missing"),
    ("market", "Market"),
    ("competition", "Competition"),
    ("evidence", "Evidence"),
    ("risks", "Risks"),
)


def claim_line(c: Claim) -> str:
    cites = "".join(f"[{s}]" for s in c.source_ids)
    tag = "" if c.epistemic == "FACT" else f" _({c.epistemic})_"
    return f"- {c.text}{(' ' + cites) if cites else ''}{tag}"


def _claims(title: str, claims: list[Claim]) -> list[str]:
    lines = [f"## {title}", ""]
    lines += [claim_line(c) for c in claims] if claims else [f"_{UNKNOWN}_"]
    return lines + [""]


def _bullets(title: str, items: list[str], empty: str = UNKNOWN) -> list[str]:
    lines = [f"## {title}", ""]
    lines += [f"- {i}" for i in items] if items else [f"_{empty}_"]
    return lines + [""]


def sources_markdown(sources: list[dict[str, Any]]) -> list[str]:
    lines = ["## Sources", ""]
    if not sources:
        return lines + ["_No sources collected._", ""]
    for s in sources:
        fetched = str(s.get("fetched_at") or "")[:10]
        meta = ", ".join(x for x in (s.get("source_type"), fetched) if x)
        lines.append(f"- **[{s['id']}]** {s.get('title') or s.get('url')} — {s.get('url')}" + (f" ({meta})" if meta else ""))
    return lines + [""]


def _legend(generator: str, model: str | None) -> str:
    how = f"generated by {model}" if generator == "llm" and model else (
        "served from cache" if generator == "cached" else "deterministic template from database facts, no LLM"
    )
    return (f"_Produced by ANTI RADAR ({how}). Claims without a tag are FACTs from the cited sources; "
            "INFERENCE and MODEL_OPINION are labeled._")


def brief_to_markdown(
    brief: AntiBrief, sources: list[dict[str, Any]], *, generator: str = "template", model: str | None = None,
    notes: list[str] | None = None,
) -> str:
    lines = [f"# Anti Brief — {brief.subject}", "", f"_{brief.date}_ · {_legend(generator, model)}", ""]
    for n in notes or []:
        lines += [f"> {n}", ""]
    for key, title in _BRIEF_SECTIONS:
        lines += _claims(title, getattr(brief, key))
    lines += _bullets("Questions to ask the founders", brief.questions_to_ask_founders, "No questions generated.")
    lines += _bullets("Unknowns", brief.unknowns, "None recorded.")
    lines += sources_markdown(sources)
    return "\n".join(lines).rstrip() + "\n"


def memo_to_markdown(
    memo: AntiMemo, sources: list[dict[str, Any]], *, generator: str = "template", model: str | None = None,
) -> str:
    lines = [f"# Anti Memo — {memo.company}", "", f"**{memo.one_liner}**", "", _legend(generator, model), "",
             "## Anti Score", "", memo.anti_score_summary, ""]
    for key, title in _MEMO_SECTIONS:
        lines += _claims(title, getattr(memo, key))
    lines += _bullets("Questions to answer", memo.questions_to_answer, "No questions generated.")
    lines += sources_markdown(sources)
    return "\n".join(lines).rstrip() + "\n"


_MEETING_SECTIONS: tuple[tuple[str, str], ...] = (
    ("context_30s", "30-second context"),
    ("why_on_radar", "Why they are on our radar"),
    ("what_they_built", "What they built"),
    ("technical_background", "Technical background"),
    ("what_changed", "What changed"),
    ("why_anti_fund", "Why Anti Fund might care"),
)


def meeting_brief_to_markdown(
    brief: MeetingBrief, sources: list[dict[str, Any]], *, generator: str = "template", model: str | None = None,
) -> str:
    lines = [f"# Meeting Brief — {brief.name}", "", f"_{brief.date}_ · {_legend(generator, model)}", ""]
    for key, title in _MEETING_SECTIONS:
        lines += _claims(title, getattr(brief, key))
    lines += _bullets("Questions to ask", brief.questions, "No questions generated.")
    lines += _bullets("Things to verify", brief.things_to_verify, "Nothing flagged.")
    lines += _bullets("Unknowns", brief.unknowns, "None recorded.")
    lines += sources_markdown(sources)
    return "\n".join(lines).rstrip() + "\n"
