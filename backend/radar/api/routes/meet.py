"""Who Should We Meet This Week (GET /meet, POST /meet/refresh) and Meeting Briefs (POST /meeting-brief).

Writes (refresh, brief generation) are POSTs, so the admin gate (``api.auth``) applies when an
``ADMIN_TOKEN`` is configured. A meeting brief is never generated by a GET.
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session

from radar.api.ratelimit import rate_limit
from radar.db import get_session
from radar.models import UserAction
from radar.schemas.api import MeetFeed, MeetingBriefRequest, ReportOut
from radar.services import entities, meet

SessionDep = Annotated[Session, Depends(get_session)]

router = APIRouter(tags=["meet"])


@router.get("/meet", response_model=MeetFeed)
def meet_feed(
    session: SessionDep,
    week: Annotated[str, Query(max_length=10, pattern=r"^(current|\d{4}-W\d{2})$")] = "current",
    include_demo: Annotated[bool | None, Query()] = None,
) -> MeetFeed:
    try:
        return meet.meet_feed(session, week, include_demo=include_demo)
    except meet.InvalidWeek as e:
        raise HTTPException(422, detail=str(e)) from None


@router.post("/meet/refresh", response_model=MeetFeed, dependencies=[Depends(rate_limit("meet-refresh", 6))])
def meet_refresh(session: SessionDep) -> MeetFeed:
    """Recompute the current week (replaces its stored ranking)."""
    meet.compute_week(session, force=True)
    session.add(UserAction(action="meet_refresh", meta={"week": meet.iso_week()}))
    session.flush()
    return meet.meet_feed(session, "current")


@router.post("/meeting-brief", response_model=ReportOut, dependencies=[Depends(rate_limit("meeting-brief", 10))])
def meeting_brief(req: MeetingBriefRequest, session: SessionDep) -> ReportOut:
    """Latest brief for the person (cached) unless ``force``; otherwise generate (LLM or template)."""
    from radar.agent.meeting import generate_meeting_brief

    person = meet.resolve_person(session, req.person_id.strip())
    if person is None:
        raise HTTPException(404, detail="Person not found")
    report = generate_meeting_brief(session, person.id, force=req.force)
    session.add(UserAction(action="meeting_brief", entity_type="person", entity_id=person.id,
                           meta={"report_id": str(report.id), "force": req.force}))
    session.flush()
    session.refresh(report)
    return entities.report_out(session, report)
