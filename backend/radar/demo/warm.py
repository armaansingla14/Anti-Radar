"""Pre-generate LLM outputs for demo mode (run once with an API key, then commit).

    radar demo warm --investigate halcyon-dynamics --investigate dexmal

1. Exercises the real API code paths (radar, daily, brief, top company/founder pages)
   so every narrative is generated by the configured LLM and stored in `llm_cache`.
2. Runs RADAR ANALYST + Anti Memo on a few showcase entities.
3. Exports the cache to demo/llm_cache.jsonl and those reports to demo/reports.jsonl.

On a fresh clone `radar seed-demo` imports both, so narratives, briefs and memos render
without any API key — labeled with the model that produced them.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

from sqlalchemy import select

from radar.db import session_scope
from radar.models import Company, Person, ResearchReport

log = logging.getLogger("radar.demo.warm")

DEMO_DIR = Path(__file__).parent
REPORTS_FILE = DEMO_DIR / "reports.jsonl"


def warm_pages(companies: int = 16, founders: int = 12) -> dict[str, int]:
    from fastapi.testclient import TestClient

    from radar.api.main import create_app

    n = {"pages": 0, "errors": 0}
    with TestClient(create_app()) as client:
        for path in ("/api/radar", "/api/daily", "/api/brief"):
            r = client.get(path)
            n["pages"] += 1
            n["errors"] += r.status_code != 200
        radar = client.get("/api/radar").json()
        slugs = [c["slug"] for c in radar.get("cards", [])]
        slugs += [c["slug"] for c in client.get("/api/companies", params={"limit": companies}).json()]
        for slug in list(dict.fromkeys(slugs))[:companies]:
            r = client.get(f"/api/companies/{slug}")
            n["pages"] += 1
            n["errors"] += r.status_code != 200
        people = [c["slug"] for c in radar.get("founders", [])]
        people += [c["slug"] for c in client.get("/api/founders", params={"limit": founders}).json()]
        for slug in list(dict.fromkeys(people))[:founders]:
            r = client.get(f"/api/founders/{slug}")
            n["pages"] += 1
            n["errors"] += r.status_code != 200
    return n


def _entity(session, slug: str) -> tuple[str, Any] | None:
    for kind, model in (("company", Company), ("person", Person)):
        row = session.scalar(select(model).where(model.slug == slug))
        if row is not None:
            return kind, row
    return None


def investigate_showcase(slugs: list[str], *, memo: bool = True, live_fetch: bool = True) -> list[str]:
    from radar.agent.analyst import investigate
    from radar.agent.memo import generate_memo

    done = []
    for slug in slugs:
        with session_scope() as s:
            found = _entity(s, slug)
            if not found:
                log.warning("warm: no entity %s", slug)
                continue
            kind, row = found
            brief = investigate(s, kind, row.id, live_fetch=live_fetch)
            done.append(f"brief:{slug}:{brief.generator}:${brief.cost_usd:.2f}")
            if memo:
                m = generate_memo(s, kind, row.id, report_id=str(brief.id))
                done.append(f"memo:{slug}:{m.generator}:${m.cost_usd:.2f}")
    return done


def export_reports(path: Path = REPORTS_FILE) -> int:
    """Write reports for entities (by slug) so they survive a reseed."""
    n = 0
    with session_scope() as s, path.open("w") as f:
        for r in s.scalars(select(ResearchReport).where(ResearchReport.kind.in_(("brief", "memo")))
                           .order_by(ResearchReport.created_at)):
            model = Company if r.entity_type == "company" else Person
            ent = s.get(model, r.entity_id) if r.entity_id else None
            if ent is None:
                continue
            f.write(json.dumps({
                "kind": r.kind, "entity_type": r.entity_type, "entity_slug": ent.slug, "title": r.title,
                "body": r.body, "markdown": r.markdown, "sources": r.sources, "model": r.model,
                "generator": r.generator, "status": r.status, "trace": r.trace, "cost_usd": r.cost_usd,
                "is_demo": r.is_demo, "created_at": r.created_at.isoformat(),
            }, default=str) + "\n")
            n += 1
    return n


def import_reports(path: Path = REPORTS_FILE) -> int:
    if not path.exists():
        return 0
    from datetime import datetime

    n = 0
    with session_scope() as s:
        for line in path.read_text().splitlines():
            d = json.loads(line)
            found = _entity(s, d["entity_slug"])
            if not found:
                continue
            _kind, row = found
            s.add(ResearchReport(
                kind=d["kind"], entity_type=d["entity_type"], entity_id=row.id, title=d["title"], body=d["body"],
                markdown=d["markdown"], sources=d["sources"], model=d["model"], generator=d["generator"],
                status=d.get("status", "complete"), trace=d.get("trace") or [], cost_usd=d.get("cost_usd") or 0.0,
                is_demo=bool(d.get("is_demo")), created_at=datetime.fromisoformat(d["created_at"]),
            ))
            n += 1
    return n
