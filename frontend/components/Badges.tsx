import clsx from "clsx";
import type { Epistemic, Verification } from "@/lib/types";

const chip = "inline-flex items-center gap-1 rounded-xs px-1.5 py-[1px] font-mono text-[9.5px] uppercase leading-[14px] tracking-[0.08em] whitespace-nowrap";

const EPISTEMIC: Record<Epistemic, { text: string; glyph: string; cls: string; title: string }> = {
  FACT: {
    text: "Fact",
    glyph: "●",
    cls: "border border-ink/70 text-ink",
    title: "Fact — directly observed in a cited source",
  },
  INFERENCE: {
    text: "Inference",
    glyph: "◆",
    cls: "border border-rule-strong text-ink-2",
    title: "Inference — derived deterministically from observed facts",
  },
  MODEL_OPINION: {
    text: "Model opinion",
    glyph: "○",
    cls: "border border-dotted border-ink-3 text-ink-2 italic",
    title: "Model opinion — generated by a language model; verify before relying on it",
  },
};

export interface EpistemicBadgeProps {
  value: Epistemic;
  /** Glyph only (title still describes it). */
  compact?: boolean;
  className?: string;
}

/** How we know a claim: FACT / INFERENCE / MODEL OPINION. */
export function EpistemicBadge({ value, compact, className }: EpistemicBadgeProps) {
  const meta = EPISTEMIC[value];
  return (
    <span className={clsx(chip, meta.cls, compact && "px-1", className)} title={meta.title} aria-label={meta.title}>
      <span aria-hidden className="text-[8px] not-italic">{meta.glyph}</span>
      {!compact && <span aria-hidden>{meta.text}</span>}
    </span>
  );
}

const VERIFICATION: Record<Verification, { cls: string; title: string }> = {
  VERIFIED: { cls: "border border-ink/70 text-ink", title: "Verified against a primary source" },
  INFERRED: { cls: "border border-rule-strong text-ink-2", title: "Inferred from indirect evidence" },
  UNKNOWN: { cls: "border border-dotted border-ink-3 text-ink-3", title: "Unknown — not established by any source" },
};

export interface VerificationBadgeProps {
  value: Verification;
  className?: string;
}

/** Field provenance: VERIFIED / INFERRED / UNKNOWN. */
export function VerificationBadge({ value, className }: VerificationBadgeProps) {
  const meta = VERIFICATION[value];
  return (
    <span className={clsx(chip, meta.cls, className)} title={meta.title}>
      {value}
    </span>
  );
}

export interface DemoBadgeProps {
  /** Optional provenance note shown as tooltip. */
  note?: string | null;
  className?: string;
}

/** Marker for synthetic data. Render whenever `is_demo` is true. */
export function DemoBadge({ note, className }: DemoBadgeProps) {
  const title = note ?? "Synthetic demo data — fictional entities, not real companies or people";
  return (
    <span className={clsx(chip, "hatch text-ink-2", className)} title={title} aria-label={title}>
      Demo data
    </span>
  );
}

export interface NewBadgeProps {
  className?: string;
}

/** Entered the radar in the last 7 days. */
export function NewBadge({ className }: NewBadgeProps) {
  return (
    <span className={clsx(chip, "border border-accent text-accent", className)} title="Entered the radar in the last 7 days">
      New
    </span>
  );
}
